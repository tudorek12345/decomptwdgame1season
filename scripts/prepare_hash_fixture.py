"""Extract a bounded x86 oracle, never execute the full analysis image.

Only the listed functions, their immutable tables, and relevant relocations are
included. Internal relative calls retain their RVA distance in the test mapping.
"""
from pathlib import Path
import hashlib,json,struct
import pefile,capstone
ROOT=Path(__file__).resolve().parents[1]
FUNCTIONS=[
    (0xcbfc0,331,'closest_point_on_segment','geometry.cpp','cdecl'),
    (0x1cc380,0xad,'crc32','hash.cpp','cdecl'),
    (0x1cc430,0x9e,'hash_words','hash.cpp','cdecl'),
    (0x1eecf0,0x47,'crc64_string','hash.cpp','cdecl'),
    (0x1eed40,0x4e,'crc64_string_ascii_fold','hash.cpp','cdecl'),
    (0x57ea0,0x10,'symbol_zero','symbol.cpp','thiscall'),
    (0x57eb0,0x1f,'symbol_from_text','symbol.cpp','thiscall'),
    (0x57ed0,0x13,'symbol_copy','symbol.cpp','thiscall'),
    (0x57ef0,0x10,'symbol_from_value','symbol.cpp','thiscall'),
    (0x57f00,0x20,'symbol_append','symbol.cpp','thiscall'),
    (0x57f20,0x09,'symbol_identity','symbol.cpp','cdecl'),
    (0x57f30,0x2d,'symbol_compare32','symbol.cpp','cdecl'),
    (0x57f60,0x27,'symbol_from_string32','symbol.cpp','thiscall'),
    (0x57f90,0x25,'symbol_assign_string32','symbol.cpp','thiscall'),
]
def main():
    source=ROOT/'sources/WalkingDead101.analysis.exe';blob=source.read_bytes()
    assert hashlib.sha256(blob).hexdigest()=='39df65b5e03e68703e04da90d516fbc15392706fbc9a4580f2aaf44ef78c33d9'
    pe=pefile.PE(data=blob);base=pe.OPTIONAL_HEADER.ImageBase
    rows=[];asm=[];md=capstone.Cs(capstone.CS_ARCH_X86,capstone.CS_MODE_32)
    for rva,length,name,file,abi in FUNCTIONS:
        code=pe.get_data(rva,length)
        rows.append({'rva':hex(rva),'span_bytes':length,'name':name,'export':'twd_'+name,
                     'source':'reconstructed/'+file,'abi':abi,'expected_prefix':code[:6].hex()})
        asm.append('\n; '+name+' RVA '+hex(rva))
        for i in md.disasm(code,base+rva):asm.append(f'{i.address-base:08x}  {i.bytes.hex():24} {i.mnemonic} {i.op_str}')
    (ROOT/'re/replacements.json').write_text(json.dumps(rows,indent=2)+'\n')
    (ROOT/'reports/hash-symbol-original.asm').write_text('\n'.join(asm)+'\n')
    ranges=[(r,l) for r,l,*_ in FUNCTIONS if r!=0xcbfc0]+[(0x58fce0,1024),(0x5923f8,2048),(0x592bf8,256)]
    relocations=[e.rva for block in pe.DIRECTORY_ENTRY_BASERELOC for e in block.entries
                 if e.type==3 and any(r<=e.rva and e.rva+4<=r+n for r,n in ranges)]
    out=['// Generated by scripts/prepare_hash_fixture.py from hash-checked local input.','#pragma once','#include <cstdint>',
         'struct OracleRange { std::uint32_t rva,size; const unsigned char* bytes; };']
    for index,(rva,n) in enumerate(ranges):
        data=pe.get_data(rva,n)
        out.append(f'inline constexpr unsigned char oracle_bytes_{index}[]={{')
        out.extend(','.join(f'0x{x:02x}' for x in data[i:i+16])+',' for i in range(0,n,16))
        out.append('};')
    out.append('inline constexpr OracleRange oracle_ranges[]={')
    out.extend(f'{{0x{r:x},{n},oracle_bytes_{i}}},' for i,(r,n) in enumerate(ranges))
    out.extend(['};','inline constexpr std::uint32_t oracle_relocations[]={'+','.join(hex(r) for r in relocations)+'};',
                f'inline constexpr std::uint32_t oracle_image_size=0x{pe.OPTIONAL_HEADER.SizeOfImage:x};'])
    (ROOT/'tests/original_hash_symbols.hpp').write_text('\n'.join(out)+'\n')
    table64=struct.unpack('<256Q',pe.get_data(0x5923f8,2048))
    generated=[]
    for index in range(256):
        c=index<<56
        for _ in range(8):c=((c<<1)^(0x42f0e1eba9ea3693 if c>>63 else 0))&0xffffffffffffffff
        generated.append(c)
    assert list(table64)==generated
    assert pe.get_data(0x592bf8,256)==bytes(i+32 if 65<=i<=90 else i for i in range(256))
    report={'input_sha256':hashlib.sha256(blob).hexdigest(),'functions':rows[1:],
            'crc64_table_rva':'0x5923f8','crc64_table_generated_exact':True,'ascii_fold_table_rva':'0x592bf8','ascii_fold_generated_exact':True,
            'oracle_relocations':list(map(hex,relocations)),
            'contract':'cdecl checksums return EAX or EDX:EAX. Symbol methods use ECX this and callee stack cleanup; fastcall DLL bridges consume unused EDX. Symbol is two ordered 32-bit words. String32 is 16-byte inline storage plus length at +16 and capacity at +20; capacity >=16 selects a 32-bit pointer at +0. CRC64 strings require a readable NUL terminator and do not accept null. Only ASCII A-Z are folded; high bytes unchanged. CRC32 null returns 0 regardless of length/seed. Word hash count is words; unaligned little-endian loads.',
            'excluded_buffer_crc64':{'rva':'0x1eec10','reason':'MOVSX without masking uses negative table indexes for bytes >=128; preceding image data includes relocatable pointers. Discovered/exported, not replaced with a falsely standard CRC algorithm.'},
            'limits':'Observed contracts, inferred semantic names. Invalid pointers, nonterminated strings, simultaneous writes and invalid capacity/storage pairs are outside the valid domain. No original string allocator or ownership is reconstructed.'}
    (ROOT/'reports/hash-contract.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({'replacements':len(rows),'oracle_ranges':len(ranges),'relocations':len(relocations)}))
if __name__=='__main__':main()
